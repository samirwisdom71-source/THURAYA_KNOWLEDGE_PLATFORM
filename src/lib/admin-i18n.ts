export function labelOf<T extends Record<string, { ar: string; en: string }>>(map: T, key: string, locale: Locale) {
  return map[key as keyof T]?.[locale] || key;
}

export function dateLocale(locale: Locale) {
  return locale === 'ar' ? 'ar-AE' : 'en-GB';
}
